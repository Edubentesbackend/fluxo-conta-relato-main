import { zodResolver } from '@hookform/resolvers/zod';
import { useForm } from 'react-hook-form';
import { z } from 'zod';
import { Button } from '@/components/ui/button';
import { Card, CardContent, CardHeader, CardTitle } from '@/components/ui/card';
import {
  Form,
  FormControl,
  FormField,
  FormItem,
  FormLabel,
  FormMessage,
} from '@/components/ui/form';
import { Input } from '@/components/ui/input';
import { Textarea } from '@/components/ui/textarea';
import { Calendar } from '@/components/ui/calendar';
import {
  Popover,
  PopoverContent,
  PopoverTrigger,
} from '@/components/ui/popover';
import { CalendarIcon } from 'lucide-react';
import { format } from 'date-fns';
import { ptBR } from 'date-fns/locale';
import { cn } from '@/lib/utils';
import { useAccounts } from '@/hooks/useAccounts';
import { useCreateTransaction } from '@/hooks/useTransactions';
import { TRANSACTION_TYPES, TransactionType } from '@/types/database';
import { useToast } from '@/hooks/use-toast';
import { useState } from 'react';
import { SearchableSelect, SearchableSelectItem } from '@/components/ui/searchable-select';
import { formatCurrencyInput, parseCurrencyInput } from '@/utils/currency';

const formSchema = z.object({
  source_account_id: z.string().min(1, 'Conta de origem é obrigatória'),
  destination_account_id: z.string().min(1, 'Conta de destino é obrigatória'),
  transaction_date: z.date({
    required_error: 'Data da transação é obrigatória',
  }),
  amount: z.number().min(0.01, 'Valor deve ser maior que zero'),
  transaction_type: z.enum(['emprestimo', 'devolucao', 'ajuste', 'rateio', 'correcao', 'estorno', 'transferencia_operacional'] as const),
  description: z.string().min(1, 'Descrição é obrigatória'),
}).refine((data) => data.source_account_id !== data.destination_account_id, {
  message: 'A conta de origem deve ser diferente da conta de destino',
  path: ['destination_account_id'],
});

type FormData = z.infer<typeof formSchema>;

interface TransactionFormProps {
  onSuccess?: () => void;
}

export const TransactionForm: React.FC<TransactionFormProps> = ({ onSuccess }) => {
  const [showConfirmation, setShowConfirmation] = useState(false);
  const [formData, setFormData] = useState<FormData | null>(null);
  
  const { data: accounts = [] } = useAccounts();
  const createTransaction = useCreateTransaction();
  const { toast } = useToast();

  const form = useForm<FormData>({
    resolver: zodResolver(formSchema),
    defaultValues: {
      source_account_id: '',
      destination_account_id: '',
      amount: 0,
      description: '',
      transaction_type: 'emprestimo',
      transaction_date: new Date(),
    },
  });

  const onSubmit = (data: FormData) => {
    setFormData(data);
    setShowConfirmation(true);
  };

  const handleConfirm = async () => {
    if (!formData) return;
    
    try {
      await createTransaction.mutateAsync({
        unique_identifier: '', // Will be auto-generated by trigger
        source_account_id: formData.source_account_id,
        destination_account_id: formData.destination_account_id,
        transaction_date: formData.transaction_date.toISOString(),
        amount: formData.amount,
        transaction_type: formData.transaction_type,
        description: formData.description,
        status: 'completed',
        parent_transaction_id: null,
      });
      
      toast({
        title: 'Sucesso',
        description: 'Transação criada com sucesso!',
        className: 'bg-success text-success-foreground border-success',
      });
      
      form.reset();
      setShowConfirmation(false);
      setFormData(null);
      onSuccess?.();
    } catch (error: any) {
      toast({
        title: 'Erro',
        description: error.message || 'Erro ao criar transação',
        variant: 'destructive',
      });
    }
  };

  const handleCancel = () => {
    setShowConfirmation(false);
    setFormData(null);
  };

  const getAccountName = (accountId: string) => {
    const account = accounts.find(acc => acc.id === accountId);
    return account ? `${account.account_number || ''} - ${account.name}` : 'Conta não encontrada';
  };

  const getTransactionTypeLabel = (type: TransactionType) => {
    return TRANSACTION_TYPES.find(t => t.value === type)?.label || '';
  };

  // Prepare account options for SearchableSelect
  const accountOptions: SearchableSelectItem[] = accounts.map(account => ({
    value: account.id,
    label: `${account.account_number || ''} - ${account.name}`,
    searchLabel: `${account.account_number || ''} ${account.name}`.toLowerCase()
  }));

  if (showConfirmation && formData) {
    return (
      <Card className="w-full max-w-2xl mx-auto shadow-lg border-0 rounded-2xl overflow-hidden">
        <CardHeader className="bg-gradient-to-r from-primary/10 to-accent/10 border-b border-border/50">
          <CardTitle className="text-primary text-xl font-semibold">Confirmar Transação</CardTitle>
        </CardHeader>
        <CardContent className="space-y-6 p-8">
          <div className="bg-muted/30 p-4 rounded-xl border border-border/50">
            <p className="text-sm text-muted-foreground text-center">
              ✨ O identificador único será gerado automaticamente após salvar
            </p>
          </div>
          
          <div className="grid grid-cols-1 md:grid-cols-2 gap-6">
            <div className="space-y-2">
              <strong className="text-sm font-semibold text-foreground">Tipo de Transação:</strong>
              <p className="text-base bg-secondary/50 px-3 py-2 rounded-lg">
                {getTransactionTypeLabel(formData.transaction_type)}
              </p>
            </div>
            
            <div className="space-y-2">
              <strong className="text-sm font-semibold text-foreground">Data:</strong>
              <p className="text-base bg-secondary/50 px-3 py-2 rounded-lg">
                {format(formData.transaction_date, 'dd/MM/yyyy', { locale: ptBR })}
              </p>
            </div>
            
            <div className="space-y-2">
              <strong className="text-sm font-semibold text-foreground">Conta de Origem:</strong>
              <p className="text-sm bg-secondary/50 px-3 py-2 rounded-lg">
                {getAccountName(formData.source_account_id)}
              </p>
            </div>
            
            <div className="space-y-2">
              <strong className="text-sm font-semibold text-foreground">Conta de Destino:</strong>
              <p className="text-sm bg-secondary/50 px-3 py-2 rounded-lg">
                {getAccountName(formData.destination_account_id)}
              </p>
            </div>
            
            <div className="space-y-2 md:col-span-2">
              <strong className="text-sm font-semibold text-foreground">Valor:</strong>
              <p className="text-2xl font-bold text-primary bg-primary/5 px-4 py-3 rounded-xl text-center">
                R$ {formData.amount.toLocaleString('pt-BR', { minimumFractionDigits: 2 })}
              </p>
            </div>
          </div>
          
          <div className="space-y-2">
            <strong className="text-sm font-semibold text-foreground">Descrição:</strong>
            <p className="text-sm bg-muted/30 p-4 rounded-xl border border-border/50 min-h-[60px]">
              {formData.description}
            </p>
          </div>
          
          <div className="flex gap-4 pt-6">
            <Button 
              onClick={handleConfirm} 
              disabled={createTransaction.isPending}
              className="flex-1 bg-primary hover:bg-primary-dark text-white font-medium py-3 rounded-xl transition-all duration-200 shadow-lg hover:shadow-xl"
            >
              {createTransaction.isPending ? 'Salvando...' : 'Confirmar Transação'}
            </Button>
            <Button 
              variant="outline" 
              onClick={handleCancel}
              className="flex-1 py-3 rounded-xl font-medium border-2 hover:bg-secondary/50 transition-all duration-200"
            >
              Cancelar
            </Button>
          </div>
        </CardContent>
      </Card>
    );
  }

  return (
    <Card className="w-full max-w-2xl mx-auto shadow-lg border-0 rounded-2xl overflow-hidden">
      <CardHeader className="bg-gradient-to-r from-primary/10 to-accent/10 border-b border-border/50">
        <CardTitle className="text-primary text-xl font-semibold">Nova Transação</CardTitle>
        <p className="text-sm text-muted-foreground mt-2">
          💫 O identificador único será gerado automaticamente
        </p>
      </CardHeader>
      <CardContent className="p-8">
        <Form {...form}>
          <form onSubmit={form.handleSubmit(onSubmit)} className="space-y-6">
            <div className="grid grid-cols-1 md:grid-cols-2 gap-6">
              <FormField
                control={form.control}
                name="source_account_id"
                render={({ field }) => (
                  <FormItem>
                    <FormLabel className="text-sm font-semibold text-foreground">Conta de Origem</FormLabel>
                    <FormControl>
                      <SearchableSelect
                        value={field.value}
                        onValueChange={field.onChange}
                        items={accountOptions}
                        placeholder="Buscar conta de origem..."
                        searchPlaceholder="Digite o número ou nome da conta"
                        emptyMessage="Nenhuma conta encontrada."
                        className="rounded-xl"
                      />
                    </FormControl>
                    <FormMessage />
                  </FormItem>
                )}
              />

              <FormField
                control={form.control}
                name="destination_account_id"
                render={({ field }) => (
                  <FormItem>
                    <FormLabel className="text-sm font-semibold text-foreground">Conta de Destino</FormLabel>
                    <FormControl>
                      <SearchableSelect
                        value={field.value}
                        onValueChange={field.onChange}
                        items={accountOptions}
                        placeholder="Buscar conta de destino..."
                        searchPlaceholder="Digite o número ou nome da conta"
                        emptyMessage="Nenhuma conta encontrada."
                        className="rounded-xl"
                      />
                    </FormControl>
                    <FormMessage />
                  </FormItem>
                )}
              />
            </div>

            <div className="grid grid-cols-1 md:grid-cols-2 gap-6">
              <FormField
                control={form.control}
                name="transaction_date"
                render={({ field }) => (
                  <FormItem className="flex flex-col">
                    <FormLabel className="text-sm font-semibold text-foreground">Data da Transação</FormLabel>
                    <Popover>
                      <PopoverTrigger asChild>
                        <FormControl>
                          <Button
                            variant="outline"
                            className={cn(
                              'w-full pl-3 text-left font-normal rounded-xl border-2 h-11',
                              !field.value && 'text-muted-foreground'
                            )}
                          >
                            {field.value ? (
                              format(field.value, 'dd/MM/yyyy', { locale: ptBR })
                            ) : (
                              <span>Selecione a data</span>
                            )}
                            <CalendarIcon className="ml-auto h-4 w-4 opacity-50" />
                          </Button>
                        </FormControl>
                      </PopoverTrigger>
                      <PopoverContent className="w-auto p-0 rounded-xl" align="start">
                        <Calendar
                          mode="single"
                          selected={field.value}
                          onSelect={field.onChange}
                          locale={ptBR}
                          disabled={(date) =>
                            date > new Date() || date < new Date('1900-01-01')
                          }
                          initialFocus
                          className="rounded-xl"
                        />
                      </PopoverContent>
                    </Popover>
                    <FormMessage />
                  </FormItem>
                )}
              />

              <FormField
                control={form.control}
                name="amount"
                render={({ field }) => {
                  const [displayValue, setDisplayValue] = useState(
                    field.value > 0 ? formatCurrencyInput(field.value.toString()) : ''
                  );

                  return (
                    <FormItem>
                      <FormLabel className="text-sm font-semibold text-foreground">Valor (R$)</FormLabel>
                      <FormControl>
                        <Input
                          type="text"
                          placeholder="0,00"
                          value={displayValue}
                          onChange={(e) => {
                            const formatted = formatCurrencyInput(e.target.value);
                            setDisplayValue(formatted);
                            const numericValue = parseCurrencyInput(e.target.value);
                            field.onChange(numericValue);
                          }}
                          className="text-right text-lg font-medium rounded-xl border-2 h-11"
                        />
                      </FormControl>
                      <FormMessage />
                    </FormItem>
                  );
                }}
              />
            </div>

            <FormField
              control={form.control}
              name="transaction_type"
              render={({ field }) => (
                <FormItem>
                  <FormLabel className="text-sm font-semibold text-foreground">Tipo de Transação</FormLabel>
                  <FormControl>
                    <SearchableSelect
                      value={field.value}
                      onValueChange={field.onChange}
                      items={TRANSACTION_TYPES.map(type => ({
                        value: type.value,
                        label: type.label
                      }))}
                      placeholder="Selecionar tipo..."
                      searchPlaceholder="Buscar tipo de transação"
                      emptyMessage="Nenhum tipo encontrado."
                      className="rounded-xl"
                    />
                  </FormControl>
                  <FormMessage />
                </FormItem>
              )}
            />

            <FormField
              control={form.control}
              name="description"
              render={({ field }) => (
                <FormItem>
                  <FormLabel className="text-sm font-semibold text-foreground">Descrição</FormLabel>
                  <FormControl>
                    <Textarea
                      placeholder="Digite a descrição da transação"
                      className="resize-none min-h-[100px] rounded-xl border-2"
                      {...field}
                    />
                  </FormControl>
                  <FormMessage />
                </FormItem>
              )}
            />

            <Button 
              type="submit" 
              className="w-full bg-primary hover:bg-primary-dark text-white font-semibold py-4 text-lg rounded-xl transition-all duration-200 shadow-lg hover:shadow-xl"
            >
              Continuar
            </Button>
          </form>
        </Form>
      </CardContent>
    </Card>
  );
};